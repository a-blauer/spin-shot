"""Sets the game's per-sound trims so each new sound plays as loud (K-weighted, loudest 100 ms) as the one it replaces
   did after its own trim: the mix that was balanced by measurement stays balanced, only the sounds change."""
import json, re, subprocess, numpy as np, os, sys
sys.path.insert(0, os.path.dirname(__file__)); from core import kwin, SR
NEW = '../../public/audio/'
def load(f):
    raw = subprocess.run(['ffmpeg', '-v', 'quiet', '-i', f, '-f', 'f32le', '-ac', '1', '-ar', str(SR), '-'], capture_output=True).stdout; return np.frombuffer(raw, dtype=np.float32).astype(float)
# how loud each sound played in the mix that was balanced by measurement (its file's level plus its trim), kept so a
# rebuilt sound can be put back at the same place
REF = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'reference_levels.json')))
M = json.load(open('/tmp/sfx_manifest.json'))
LIKE = dict(S_Zap=('S_Chain', 0), S_Frost=('S_Ricochet', -1), S_Swing=('S_Dash', -3), S_SwingBig=('S_Dash', -1), S_Blade=('S_HitFlesh2', 1), S_Blunt=('S_HitFlesh2', 2), S_Blink=('S_Wings', 4), S_Shield=('S_Door', 0),
            S_ShieldBreak=('S_Door', 1), S_Tide=('S_Wings', 2), S_Part=('S_Upgrade', -3), S_Fit=('S_Upgrade', -1), S_Unfit=('S_Upgrade', -4), S_Bench=('S_Switch', 4), S_Clear=('S_LevelUp', 0), S_Enter=('S_Door', 1),
            S_Phase=('S_BossRoar', 0), S_Revive=('S_PowerUp', 0), S_Bell=('S_LevelUp', -3), S_Pickup=('S_Upgrade', -5))
def old_level(n): return REF[n]
trim = {}; note = []; var = {}
amb = old_level('S_AmbWind')
for name in sorted(M):
    base = re.sub(r'_\d+$', '', name)
    if base != name: var[base] = max(var.get(base, 1), int(name.rsplit('_', 1)[1]) + 1)
    if name.startswith('S_Amb'): tgt = old_level(name) if name in ('S_AmbWind', 'S_AmbCasino') else amb
    elif base in REF and base not in LIKE: tgt = old_level(base)
    elif base in LIKE: tgt = old_level(LIKE[base][0]) + LIKE[base][1]
    else: note.append('no reference for ' + name); continue
    trim[name] = round(10 ** ((tgt - kwin(load(NEW + name + '.mp3'))) / 20), 2)
loops = {n: [0.5, round(M[n]['dur'] - 0.5, 3)] for n in M if n.startswith('S_Amb')}
js = ("// Generated by tools/sfx/calib.py: do not edit by hand. TRIM puts each file where the mix was balanced (loudest 100 ms,\n"
      "// K-weighted); VAR is how many takes a sound has (S_Name, S_Name_1, ...); LOOPS are the seamless regions of the room tones.\n"
      "export const TRIM = " + json.dumps(trim).replace('"', '') + ";\nexport const VAR = " + json.dumps(var).replace('"', '') + ";\nexport const LOOPS = " + json.dumps(loops).replace('"', '') + ";\n")
open('../../src/audio_trim.js', 'w').write(js)
print(len(trim), 'trims', len(var), 'with takes', note, 'range', min(trim.values()), max(trim.values()), {k: v for k, v in trim.items() if v > 2.0 or v < 0.4})
