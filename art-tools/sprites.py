"""
Renders all Dead Man's Hand creature puppet parts to PNG (RawArt/Sprites/Creatures)
and writes Source/DeadMansHand/DMHSprites.inl (part table: texture, role, layer,
pivot, offset, size).  Also writes a composite preview sheet.

  python3 tools/art/sprites.py [--preview-only]
"""
import io
import json
import math
import os
import sys

import cairosvg
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import vectorkit  # noqa: E402
PACK = int(sys.argv[1]) if len(sys.argv) > 1 else 0   # 0 = Deadwater Gulch; 1.. = one pack of creatures per extra map
ROSTER = __import__('creatures' if PACK == 0 else 'creatures_m%d' % PACK).ROSTER

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(ROOT, 'RawArt', 'Sprites', 'Creatures' + (str(PACK) if PACK else ''))
PREVIEW = os.path.join(ROOT, 'RawArt', 'preview')
PX_PER_UNIT = 1.4     # texture resolution (design units are 0.5 cm)
CM_PER_UNIT = 0.5


def render_png(svg, w, h):
    data = cairosvg.svg2png(bytestring=svg.encode('utf-8'), output_width=w, output_height=h)
    return Image.open(io.BytesIO(data)).convert('RGBA')


def build():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(PREVIEW, exist_ok=True)
    table = []
    sheet_imgs = []
    for cname, fn in ROSTER:
        parts = fn()
        rendered = []
        for p in parts:
            svg, pw, ph, off, size = vectorkit.render_part(p, scale=PX_PER_UNIT, max_px=1024)
            img = render_png(svg, pw, ph)
            fname = 'T_%s.png' % p.name
            vectorkit.bleed(img).save(os.path.join(OUT, fname))
            rendered.append((p, img, off, size))
            table.append({
                'creature': cname, 'name': p.name, 'tex': 'T_' + p.name, 'role': p.role, 'layer': p.layer,
                'pivot': [p.pivot[0] * CM_PER_UNIT, p.pivot[1] * CM_PER_UNIT],
                'offset': [off[0] * CM_PER_UNIT, off[1] * CM_PER_UNIT],
                'size': [size[0] * CM_PER_UNIT, size[1] * CM_PER_UNIT],
            })
        sheet_imgs.append((cname, compose(rendered)))
    # preview sheet
    cols = 6
    cell = 420
    rows = (len(sheet_imgs) + cols - 1) // cols
    sheet = Image.new('RGBA', (cols * cell, rows * cell), (34, 58, 62, 255))
    for i, (cname, im) in enumerate(sheet_imgs):
        im.thumbnail((cell - 16, cell - 16))
        x = (i % cols) * cell + (cell - im.width) // 2
        y = (i // cols) * cell + (cell - im.height) - 8
        sheet.alpha_composite(im, (x, y))
    sheet.save(os.path.join(PREVIEW, 'creatures%s.png' % (PACK or '')))
    with open(os.path.join(OUT, 'parts.json'), 'w') as f:
        json.dump(table, f, indent=1)
    if PACK == 0:
        write_inl(table)
    print('rendered %d parts for %d creatures' % (len(table), len(ROSTER)))


def compose(rendered):
    """Assemble a creature from its parts in rest pose (for previews)."""
    s = PX_PER_UNIT
    boxes = []
    for p, img, off, size in rendered:
        cx = (p.pivot[0] + off[0]) * s
        cy = (p.pivot[1] + off[1]) * s
        boxes.append((cx - img.width / 2, cy + img.height / 2, img))
    minx = min(b[0] for b in boxes)
    maxy = max(b[1] for b in boxes)
    maxx = max(b[0] + b[2].width for b in boxes)
    miny = min(b[1] - b[2].height for b in boxes)
    W, H = int(maxx - minx) + 4, int(maxy - miny) + 4
    canvas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    order = sorted(range(len(rendered)), key=lambda i: rendered[i][0].layer)
    for i in order:
        x0, ytop, img = boxes[i]
        canvas.alpha_composite(img, (int(x0 - minx), int(maxy - ytop)))
    return canvas


ROLE_ENUM = {'Body': 'Body', 'Head': 'Head', 'ArmBack': 'ArmBack', 'ArmFront': 'ArmFront', 'LegBack': 'LegBack',
             'LegFront': 'LegFront', 'Tail': 'Tail', 'WingBack': 'WingBack', 'WingFront': 'WingFront', 'Prop': 'Prop'}


def write_inl(table):
    path = os.path.join(ROOT, 'Source', 'DeadMansHand', 'DMHSprites.inl')
    lines = ['// GENERATED by tools/art/sprites.py - do not edit.',
             '// { Creature, Texture, Role, Layer, PivotX, PivotZ, OffsetX, OffsetZ, SizeX, SizeZ } (cm, puppet space: +X faces right, +Z up)']
    for t in table:
        lines.append('{ TEXT("%s"), TEXT("%s"), EDMHPartRole::%s, %.2ff, %.2ff, %.2ff, %.2ff, %.2ff, %.2ff, %.2ff },' % (
            t['creature'], t['tex'], ROLE_ENUM[t['role']], t['layer'], t['pivot'][0], t['pivot'][1],
            t['offset'][0], t['offset'][1], t['size'][0], t['size'][1]))
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    build()
